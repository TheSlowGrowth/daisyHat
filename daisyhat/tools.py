
def print_big_headline(text):
    print("")
    print("#######################################################################")
    print(text)
    print("#######################################################################")
    print("")


def print_small_headline(text):
    print("")
    print("-----------------------------------------------------------------------")
    print(text)
    print("-----------------------------------------------------------------------")
    print("")

def print_warning(text):
    print("WARNING: " + str(text))

def print_info(text):
    print("INFO: " + str(text))