#pragma once
#include <array>
#include <cstdint>

namespace i2c_transfer
{
    // the sequences of bytes sent in every round.
    // alice transmits kSequenceAliceToBob and asserts on kSequenceBobToAlice;
    // bob transmits kSequenceBobToAlice and asserts on kSequenceAliceToBob.
    // they are distinct, so a wire short or stuck bit would be caught.
    constexpr std::array<uint8_t, 32> kSequenceAliceToBob = {{
        0x00, 0xFF, 0xAA, 0x55, 0x0F, 0xF0, 0x01, 0xFE,
        0x80, 0x7F, 0xC0, 0x3F, 0x3C, 0xC3, 0x03, 0xFC,
        0xDE, 0xAD, 0xBE, 0xEF, 0xBA, 0xAD, 0xF0, 0x0D,
        0xCA, 0xFE, 0xBA, 0xBE, 0x00, 0x55, 0xAA, 0xFF,
    }};
    constexpr std::array<uint8_t, 32> kSequenceBobToAlice = {{
        0x5A, 0xA5, 0xF0, 0x0F, 0x3C, 0xC3, 0x24, 0xDB,
        0x81, 0x7E, 0xF0, 0x0F, 0x69, 0x96, 0xFE, 0x01,
        0x13, 0x37, 0x13, 0x37, 0x20, 0x60, 0x0B, 0xF4,
        0x0B, 0xF4, 0x20, 0x60, 0x5A, 0xA5, 0x55, 0xAA,
    }};
} // namespace i2c_transfer
